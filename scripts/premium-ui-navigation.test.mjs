import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const file = name => readFileSync(new URL("../"+name,import.meta.url),"utf8");
const player=file("app/GreekTubePlayer.tsx");
const router=file("app/NavigationAwareGreekTubePlayer.tsx");
const profile=file("app/UserProfileEnhancer.tsx");
const settingsIcon=file("app/SettingsIcon.tsx");
const auditEnhancer=file("app/PlayerUIAuditEnhancer.tsx");
const mobilePolish=file("app/mobile-player-polish-7-8-44.css");
const globalsCss=file("app/globals.css");
const theme=file("app/ThemeToggleEnhancer.tsx");
const account=file("app/account/AccountPage.tsx");
const headerCss=file("app/header-controls-v7-12-6.css");
const railCss=file("app/premium-header-watch-rail-v7-12-5.css");
const layout=file("app/layout.tsx");
const pkg=JSON.parse(file("package.json"));

assert.ok(player.includes('data-gts-settings-trigger="true"'),"Settings nav has stable trigger");
assert.ok(router.includes('button[data-gts-settings-trigger="true"]'),"Settings deeplink finds trigger even on closed mobile menu");
assert.ok(profile.includes('href="/?view=settings"'),"Menu settings route matches router");
assert.ok(account.includes('href="/?view=settings"'),"Account settings route matches router");
assert.ok(profile.includes('event.preventDefault();window.dispatchEvent(new Event("greektube:open-settings"))'),"Home SPA menu must open settings in place");
assert.ok(player.includes('window.addEventListener("greektube:open-settings",openSettings)'),"Home must listen for settings event");
assert.ok(player.includes('import SettingsIcon from "./SettingsIcon";'),"Player renders shared settings sliders");
assert.ok(profile.includes('import SettingsIcon from "./SettingsIcon";'),"Profile menu renders same settings sliders");
assert.ok(!player.includes('>⚙</button>'),"Old emoji gear is not rendered");

const slot=(name)=>`className="${name}"`;
assert.equal(player.split(slot("gts-header-actions")).length-1,4,"Viewer, both settings overlays and home each have a stable actions group");
assert.equal(player.split(slot("gts-theme-slot")).length-1,4,"Every home/player/settings header has theme slot");
assert.equal(player.split(slot("gts-profile-slot")).length-1,4,"Every home/player/settings header has profile slot");
assert.ok(account.includes(slot("gts-profile-slot")),"Account has its own right profile slot");
assert.ok(theme.includes('.settings-screen-layer .gts-theme-slot'),"Theme portal prefers visible overlay slot");
assert.ok(profile.includes('.settings-screen-layer .gts-profile-slot'),"User profile portal prefers visible overlay slot");
assert.ok(!theme.includes('<style>{`'),"Remove inline header positioning cascade");
assert.ok(!layout.includes('import "./v7-8-12-theme-toggle.css";'),"Legacy absolute-position theme stylesheet retired");
assert.ok(layout.includes('import "./header-controls-v7-12-6.css";'),"Canonical header sheet loaded");
assert.ok(headerCss.includes('grid-template-columns:minmax(0,auto) minmax(0,1fr) minmax(0,auto)'),"Viewer header has 3 real grid columns");
assert.ok(headerCss.includes('position:relative!important'),"Actions use document flow instead of absolute positioning");
assert.ok(headerCss.includes('.user-profile-menu .user-menu-icon svg'),"Menu uses compact icons");
assert.ok(headerCss.includes('.app-shell.account-shell'),"Account profile aligns right");
assert.ok(headerCss.includes('@media(max-width:390px)'),"Very small iPhones supported");
assert.ok(railCss.includes('.continue-row > .continue-card'),"Compact continue rail kept independent");
assert.ok(railCss.includes('scroll-snap-type:x mandatory'),"Continue rail snaps on mobile");
assert.ok(railCss.includes('html[data-theme="light"]'),"Continue rail has light scheme");
assert.ok(!railCss.includes('.user-profile-menu'),"Watch rail no longer mixes header styles");
assert.ok(pkg.version.split(".").slice(0,2).join(".")==="7.12"&&Number(pkg.version.split(".")[2])>=6,"Header slot architecture remains tested in later 7.12 releases");
assert.doesNotMatch(auditEnhancer,/\.icon-button\[aria-label="Ρυθμίσεις"\]::before/,"SVG gear cannot coexist with injected pseudo gear");
assert.doesNotMatch(mobilePolish,/\.icon-button\[aria-label="Ρυθμίσεις"\]::before/,"Mobile CSS must not recreate a second gear");
assert.doesNotMatch(auditEnhancer,/MutationObserver/,"Retired pseudo-icon cleanup should not observe entire body");
assert.ok(!layout.includes('import "./release-lock-7-8-44.css";'),"Obsolete CSS that hides SVG and injects gear must not load");
assert.doesNotMatch(globalsCss,/\.viewer \.icon-button:after\s*\{/, "Globals cannot inject another icon");
assert.ok(settingsIcon.includes('M3.5 7h7M16 7h4.5'),"Settings icon uses the requested horizontal sliders symbol");
assert.ok(!player.includes("SettingsGearIcon"),"No legacy gear component should remain");
assert.ok(!profile.includes('{message&&<p role="status">{tr(message)}</p>}'),"No stale username availability messages in the main profile dropdown");
assert.ok(profile.includes('className={`profile-availability ${availability}`}'),"Username availability feedback remains in the name editor");
assert.equal((player.match(/<SettingsIcon\/>/g)||[]).length,3,"All three player/settings header icon buttons render the same sliders SVG");
assert.ok(profile.includes('if (kind === "settings") return <SettingsIcon/>'),"The profile menu uses the identical shared icon");

assert.equal((profile.match(/href="\/account"/g)||[]).length,1,"Profile dropdown must expose exactly one account navigation link");
assert.ok(profile.includes('className="user-profile-summary user-profile-summary-link"'),"The named profile summary is the clickable account link");
assert.ok(!profile.includes('tr("Ανώνυμο προφίλ")'),"A named device profile must not be labelled anonymous in the menu");
assert.ok(profile.includes('profile.anonymous ? tr("Προφίλ συσκευής") : tr("Προσωπικό προφίλ")'),"Display accurate device-profile and personal-profile labels");
assert.ok(headerCss.includes('.user-profile-summary-link:focus-visible'),"Clickable profile summary remains keyboard accessible");
assert.ok(headerCss.includes('.user-profile-summary-link:hover'),"Clickable profile summary provides a hover state");

console.log("Header slots, account alignment, SPA settings navigation, light/mobile and independent watch-rail regression checks passed.");
