import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { latestViewedAt, pickHomeFeaturedVideo, preferredWatchState } from "../app/home-featured-selection.ts";
import { editorialVideoTitle } from "../app/editorial-video-titles.ts";

const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const oldest={id:"old_video_1",addedAt:"2026-06-01T12:00:00Z",lastWatched:"2026-10-26T10:00:00Z",lastPosition:175,progress:33};
const newer={id:"new_video_2",addedAt:"2026-10-25T12:00:00Z",lastWatched:"2026-10-26T14:30:00Z",lastPosition:640,progress:94};
const newest={id:"new_video_3",addedAt:"2026-10-26T13:00:00Z",lastPosition:0,progress:0};
assert.equal(pickHomeFeaturedVideo([newest,oldest,newer])?.id,newer.id,"most recently watched always wins, including completed");
assert.equal(pickHomeFeaturedVideo([newest,oldest])?.id,oldest.id,"history wins over newest published item");
assert.equal(pickHomeFeaturedVideo([newest,{...oldest,lastWatched:undefined}])?.id,newest.id,"guest defaults to newest added");
assert.equal(pickHomeFeaturedVideo([{...newest,libraryVisible:false}, {...oldest,lastWatched:undefined}])?.id,oldest.id,"hidden videos never featured");
assert.equal(pickHomeFeaturedVideo([]),null);
assert.equal(Number.isFinite(latestViewedAt({id:"x",addedAt:"2026-01-01"})),false);
const merged=preferredWatchState(oldest,{...oldest,lastWatched:"2026-10-25T11:00:00Z",lastPosition:0,progress:0});
assert.equal(merged.lastPosition,175,"newer local progress survives delayed older server state");
assert.equal(merged.lastWatched,oldest.lastWatched);
assert.equal(preferredWatchState(oldest,newer).lastPosition,640,"newer server state stays authoritative");
const title=editorialVideoTitle("xYB6uYyRjCA","old fatigue headline");
assert.ok(title.includes("Θυρεοειδής")&&!/κόπωσ|κουρασμ/i.test(title),"editorial title covers video without fatigue framing");
assert.equal(editorialVideoTitle("not_matching","keep existing"),"keep existing");

const player=read("app/GreekTubePlayer.tsx");
const api=read("app/api/state/route.ts");
const page=read("app/page.tsx");
const layout=read("app/layout.tsx");
const css=read("app/home-loading-polish-v7-12-3.css");
assert.match(player,/useState<AppState>\(\{videos:\[\],moments:\[\],settings:DEFAULT_SETTINGS\}\)/,"initial render must not contain old seed");
assert.match(player,/\{!hydrated&&<section className="featured featured-loading"/,"skeleton is visible before hydration");
assert.match(player,/\{hydrated&&featured&&<section/,"do not show featured until loaded");
assert.match(player,/pickHomeFeaturedVideo\(libraryVideos\)/,"home uses latest-watch chooser");
assert.match(player,/patchVideo\(video\.id,\{views:\(video\.views\|\|0\)\+1,lastWatched:new Date\(\)\.toISOString\(\)\}\)/,"opening video updates watch history");
assert.match(player,/target\.seekTo\(start,true\)/,"YouTube player seeks to saved position");
assert.match(player,/pendingPlayerStart\.current=start\?\?video\.lastPosition/,"default resume comes from saved video");
assert.match(player,/const \[libraryLoadFailed,setLibraryLoadFailed\]/,"failed load does not fake loaded content");
assert.match(api,/personal_states/,"preserve existing personal history data store");
assert.match(api,/editorialVideoTitle/,"API returns new video title");
assert.match(page,/editorialVideoTitle/,"shared preview title updated");
assert.match(layout,/home-loading-polish-v7-12-3\.css/);
assert.match(css,/::selection/,"text selection has readable colors");
assert.doesNotMatch(player,/void saveStateToServer\(fallbackState\)/,"do not overwrite server with stale local cache during hydration");
console.log("home loading, account history, resume, guest selection, title and selection tests passed");
